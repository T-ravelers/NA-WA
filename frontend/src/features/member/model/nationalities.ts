export type NationalityCode = (typeof NATIONALITY_CODES)[number]

export function isNationalityCode(value: string): value is NationalityCode {
  return (NATIONALITY_CODES as readonly string[]).includes(value)
}

/**
 * 현재 언어로 쓴 나라 이름. 모르는 코드는 `null`이고, 화면은 그때 국적 줄을 그리지 않는다.
 *
 * **위 목록에 있는 코드만 이름을 찾는다.** `Intl.DisplayNames`는 예약 코드 `ZZ`에
 * `Unknown Region`처럼 **코드와 다른 이름**을 돌려주기 때문에, "이름이 코드와 같으면
 * 모르는 것"이라는 판정만으로는 새어 나간다. 실제로 `From Unknown Region`이 찍혔다.
 */
export function nationalityName(code: string | null | undefined, locale: string): string | null {
  if (code === null || code === undefined || !isNationalityCode(code)) {
    return null
  }

  try {
    const name = new Intl.DisplayNames([locale], { type: 'region' }).of(code)
    return name === undefined || name === code ? null : name
  } catch {
    return null
  }
}

/** 현재 언어의 나라 이름으로 정렬한 선택지. 로케일이 바뀌면 순서도 바뀐다. */
export function nationalityOptions(locale: string): { code: NationalityCode; name: string }[] {
  const collator = new Intl.Collator(locale)

  return NATIONALITY_CODES.map((code) => ({
    code,
    name: nationalityName(code, locale) ?? code,
  })).sort((a, b) => collator.compare(a.name, b.name))
}
